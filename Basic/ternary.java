public class ternary { // Defines the ternary class
    public static void main(String[] args) { // Main method, entry point of the program
        int a = 10, b = 20; // Declares and initializes two integer variables a and b
        int max = (a > b) ? a : b; // Uses ternary operator to find the maximum of a and b
        System.out.println("The maximum value is: " + max); // Prints the maximum value
    }
}
